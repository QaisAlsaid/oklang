#!/usr/bin/env bash
# regenerates tests/fuzz/crosscheck-manifest.txt - the native parser's
# verdict for every .ok/.bin under the e2e corpus and the fuzz corpus -
# and tests/fuzz/corpus/checksums, the fnv1a64 integrity pins the fuzzer
# verifies at corpus load (the 4ad2cbd lesson: a landing medium can
# replace invalid utf-8 with U+FFFD; the binary seeds regenerate from
# ascii escapes so the medium never gets the last word).
# the tree-sitter sweep (Q's repo) diffs the grammar against the committed
# manifest; drift in either direction is a bug (the patch-16 discipline).
# usage: crosscheck.sh [path-to-okfuzz]   (any cwd)
set -eu
OKFUZZ="${1:-./build-gcc/okfuzz}"
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"

# the healer first: binary seeds rewrite from gen.sh's ascii escapes
# before anything walks them, so a mangled landing cannot poison the
# manifest or the pins being regenerated.
bash "$HERE/corpus/gen.sh"

{
  echo "# the tree-sitter cross-check manifest (P5): the native parser's verdict"
  echo "# for every .ok/.bin under the two committed roots. regenerated by"
  echo "# tests/fuzz/crosscheck.sh; the grammar sweep (tree-sitter-oklang) diffs"
  echo "# against this - drift in either direction is a bug."
  echo "# root: tests/e2e/tests"
  "$OKFUZZ" --crosscheck "$ROOT/tests/e2e/tests" | grep -v '^crosscheck:'
  echo "# root: tests/fuzz/corpus"
  "$OKFUZZ" --crosscheck "$ROOT/tests/fuzz/corpus" | grep -v '^crosscheck:'
  echo "# end of manifest"
} > "$ROOT/tests/fuzz/crosscheck-manifest.txt"
echo "manifest written: $ROOT/tests/fuzz/crosscheck-manifest.txt"

{
  echo "# the corpus integrity pins: fnv1a64 of every seed's bytes, names"
  echo "# relative to tests/fuzz/corpus, walk order. verified by okfuzz at"
  echo "# corpus load (both consuming lanes); binary seeds regenerate from"
  echo "# gen.sh, so a seed failing its pin is either an unregen'd change"
  echo "# or a mangled landing - run crosscheck.sh to settle both."
  "$OKFUZZ" --checksums "$ROOT/tests/fuzz/corpus"
} > "$ROOT/tests/fuzz/corpus/checksums"
echo "pins written: $ROOT/tests/fuzz/corpus/checksums"
