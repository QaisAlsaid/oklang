#!/usr/bin/env bash
# regenerates tests/fuzz/crosscheck-manifest.txt - the native parser's
# verdict for every .ok/.bin under the e2e corpus and the fuzz corpus.
# the tree-sitter sweep (Q's repo) diffs the grammar against the committed
# manifest; drift in either direction is a bug (the patch-16 discipline).
# usage: crosscheck.sh [path-to-okfuzz]   (any cwd)
set -u
OKFUZZ="${1:-./build-gcc/okfuzz}"
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
{
  echo "# the tree-sitter cross-check manifest (P5): the native parser's verdict"
  echo "# for every .ok/.bin under the two committed roots. regenerated by"
  echo "# tests/fuzz/crosscheck.sh; the grammar sweep (tree-sitter-oklang) diffs"
  echo "# against this - drift in either direction is a bug."
  echo "# root: tests/e2e/tests"
  "$OKFUZZ" --crosscheck "$ROOT/tests/e2e/tests" | grep -v '^crosscheck:'
  echo "# root: tests/fuzz/corpus"
  "$OKFUZZ" --crosscheck "$ROOT/tests/fuzz/corpus" | grep -v '^crosscheck:'
  echo "# end of manifest"
} > "$ROOT/tests/fuzz/crosscheck-manifest.txt"
echo "manifest written: $ROOT/tests/fuzz/crosscheck-manifest.txt"
